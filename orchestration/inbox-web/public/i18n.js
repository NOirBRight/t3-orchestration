export function chooseLanguage(saved, browser = '') { return saved === 'zh' || saved === 'en' ? saved : /^zh\b/i.test(browser) ? 'zh' : 'en'; }
export function translate(language, key, ...values) {
  if (key === 'hoursMinutes') return language === 'zh' ? `${values[0]} 小时${values[1] ? ` ${values[1]} 分` : ''}` : `${values[0]}h${values[1] ? ` ${values[1]}m` : ''}`;
  const text = messages[key]?.[language === 'zh' ? 0 : 1] ?? key;
  return text.replace(/\{(\d+)\}/g, (_, index) => String(values[index] ?? ''));
}

export function translateError(language, message) {
  if (language === 'zh' || messages[message]) return translate(language, message);
  return /[\u4e00-\u9fff]/.test(message) ? translate(language, 'genericError') : message;
}
